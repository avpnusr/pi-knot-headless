import { redact, fmtTokens, type State, type Question, type AgentRow, type Orchestrator } from "./core.ts";

export function esc(text: string, max = 80): string {
	let t = String(text).replace(/\s+/g, " ").trim();
	if (t.length > max) t = `${t.slice(0, max - 1)}…`;
	return t.replace(/([\\`*_{}\[\]<>#|~@])/g, "\\$1").replace(/:\/\//g, ":\\//").replace(/www\./gi, "www\u200b."); // no live links, mentions or images
}

/** Multi-line text as a fenced code block: literal (no markdown can fire inside), redacted before it is capped, with a fence longer than any backtick run in the text so it cannot break out. */
export function codeBlock(text: string, secrets: string[] = [], max = 1500): string[] {
	const t = redact(String(text), secrets).slice(0, max).replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n").trim();
	const fence = "`".repeat(Math.max(2, ...(t.match(/`+/g) ?? []).map((m) => m.length)) + 1);
	return [fence, ...t.split("\n"), fence];
}

/** For plain-text comment bodies: neutralise image/link syntax, bare URLs and @mentions without adding backslashes everywhere. */
export function defang(text: string): string {
	return text
		.replace(/!\[/g, "! [")
		.replace(/\]\(/g, "] (")
		.replace(/\/(?=\/)/g, "/\u200b") // every // in a run of slashes
		.replace(/\]:/g, "] :") // no reference-link definitions
		.replace(/www\./gi, "www\u200b.")
		.replace(/</g, "<\u200b")
		.replace(/@/g, "@\u200b");
}

const PALETTE = ["🟣", "🔵", "🟢", "🟡", "🟠", "🟤"]; // colored circles that render as emoji everywhere (⚫⚪ fall back to text glyphs)
const GLYPH: Record<string, string> = { working: "▶", done: "✅", failed: "❌", waiting: "⏳", idle: "💤", paused: "⏸" };
const BY: Record<string, string> = { model: "🤖", user: "👤", timeout: "⏱", system: "🔄" };
const MAX_AGENTS = 20;
const MAX_DECISIONS_SHOWN = 8;
const MAX_QUESTIONS = 10;

const dot = (s: State, name: string): string => {
	const i = s.dots?.[name];
	if (i !== undefined) return PALETTE[i % PALETTE.length];
	let h = 5381; // fallback for states without assigned dots
	for (const c of name) h = ((h << 5) + h + c.codePointAt(0)!) >>> 0;
	return PALETTE[h % PALETTE.length];
};
const code = (t: string, max = 60): string => `\`${String(t).replace(/[`\n\r]/g, " ").trim().slice(0, max)}\``;

const agentRow = (s: State, a: AgentRow, e: (t: string, max?: number) => string): string => {
	const nested = a.nested ? ` +${a.nested}${a.nestedTruncated ? "+" : ""} nested` : "";
	return `| ${dot(s, a.name)} | ${e(a.name, 40)}${nested} | ${e(a.model, 40)} | ${GLYPH[a.state] ?? "•"} ${a.state} | ${e(a.task)} |`;
};

export function render(s: State, o: { now: number; tz?: string; secrets?: string[] }): string {
	const secrets = o.secrets ?? [];
	const e = (t: string, max = 80) => esc(redact(t, secrets), max);
	const hm = (ts: number) =>
		new Intl.DateTimeFormat("en-GB", { hour: "2-digit", minute: "2-digit", hour12: false, timeZone: o.tz }).format(ts);
	const waiting = s.questions.length ? `⏳ waiting on you: ${s.questions.map((q) => q.id).join(", ")}` : "";
	const icon = s.phase === "ended" ? "✅" : s.phase === "running" ? "▶" : waiting ? "⏳" : "💤";
	const label = s.phase === "running" ? `▶ running${waiting ? ` · ${waiting}` : ""}` : s.phase === "idle" ? waiting || "💤 idle — no open question; comment to give a new task" : "✅ ended";
	const L: string[] = [];

	L.push(`# ${icon} ${e(s.title, 100)}`, "");
	L.push(`> ${label} · started ${hm(s.startedAt)} · heartbeat ${hm(s.lastBeat)}`, "");
	if (s.sessionId && /^[\w-]{8,64}$/.test(s.sessionId)) L.push(`🔁 \`pi --session ${s.sessionId}\``, "");
	if (s.summary) L.push(`🧭 ${e(s.summary.text, 240)} · _generated by ${e(s.summary.model, 60)}_`, "");
	L.push("## 🧠 Head", "", `${code(redact(s.headModel, secrets))}${s.headActivity ? ` — ${e(s.headActivity)}` : ""}`, "");

	L.push("## ❓ Needs you", "");
	if (s.questions.length === 0) L.push(s.phase === "ended" ? "_session ended, nothing open_" : `_no open question as of ${hm(s.lastBeat)}. The page refreshes at least every 5 minutes: an older heartbeat means this page is stale and its silence means nothing._`, "");
	for (const q of s.questions.slice(0, MAX_QUESTIONS)) L.push(...question(q, e, hm));
	if (s.questions.length > MAX_QUESTIONS) L.push(`_+${s.questions.length - MAX_QUESTIONS} more questions_`, "");

	if (s.lastMessage) {
		L.push(`## 💬 Last message from the agent · ${hm(s.lastMessage.at)}`, "");
		L.push(...codeBlock(s.lastMessage.text, secrets));
		L.push("", "_pi's tool approvals and dialogs are not visible here; something is due only if the message above or an open question says so._", "");
	}

	L.push("## 🤖 Agents", "");
	if (s.orchestrators?.length) L.push(...agentGroups(s, e));
	else if (s.agents.length === 0) L.push("_no subagents yet_", "");
	else {
		L.push("| | Agent | Model | State | Task |", "|---|---|---|---|---|");
		for (const a of s.agents.slice(-MAX_AGENTS)) L.push(agentRow(s, a, e));
		if (s.agents.length > MAX_AGENTS) L.push("", `_+${s.agents.length - MAX_AGENTS} older not shown_`);
		L.push("");
	}

	if (s.phase !== "ended") {
		const u = usageLines(s);
		if (u.length) L.push("## 💰 Usage so far", "", ...u, "");
	}

	L.push("## 📝 Decisions reported", "");
	if (s.decisions.length === 0) L.push("_none yet_", "");
	else {
		const shown = s.decisions.slice(-MAX_DECISIONS_SHOWN).reverse();
		for (const d of shown) L.push(`- ${hm(d.ts)} ${BY[d.by] ?? "•"} ${e(d.text, 160)}`);
		const older = s.decisions.length - shown.length;
		if (older > 0) L.push("", `_+${older} older_`);
		L.push("");
	}

	if (s.phase === "ended") {
		const mins = Math.max(0, Math.round((s.lastBeat - s.startedAt) / 60_000));
		const dur = mins >= 60 ? `${Math.floor(mins / 60)}h ${mins % 60}m` : `${mins}m`;
		const models = [...new Set([s.headModel, ...s.agents.map((a) => a.model)].filter(Boolean))];
		L.push("## ✅ Summary", "", `- duration: ${dur}`, `- models: ${models.map((m) => code(redact(m, secrets))).join(", ")}`);
		L.push(...outcomeLines(s));
		if (s.backgroundRunning > 0) L.push(`- ⚠️ ${s.backgroundRunning} background runs still running; results not delivered`);
		L.push("");
	}

	L.push("## 💬 How to answer", "", "Reply **in the question's comment thread**, or comment `Q1 2` (option 2) / `Q1: your text`. Any other comment is sent to the session as a message.", "");
	return L.join("\n");
}

/** Agents section with groups: collapsed bullets first (ascending n), then expanded sections (every running + the highest-n other), then Direct subagents. */
function agentGroups(s: State, e: (t: string, max?: number) => string): string[] {
	const orchs = [...s.orchestrators!].sort((a, b) => a.n - b.n);
	const lastRest = Math.max(...orchs.filter((o) => o.state !== "running").map((o) => o.n));
	const expanded = (o: Orchestrator) => o.state === "running" || o.n === lastRest;
	const workers = (o: Orchestrator) => `${o.workers}${o.truncated ? "+" : ""} ${o.workers === 1 ? "worker" : "workers"}`;
	const known = new Set(orchs.map((o) => o.id));
	const direct = s.agents.filter((a) => !a.orch || !known.has(a.orch));
	const expOrchs = orchs.filter(expanded);
	// one cap for the whole page, in page order (expanded workers by ascending n, then direct rows) — the grouped view must not grow past the flat view's 20 rows
	const candidates = [...expOrchs.flatMap((o) => s.agents.filter((a) => a.orch === o.id)), ...direct];
	const visible = new Set(candidates.slice(-MAX_AGENTS));
	const table = (title: string, col: string, rows: AgentRow[]): string[] => {
		const L = [title, "", `| | ${col} | Model | State | Task |`, "|---|---|---|---|---|"];
		for (const a of rows) if (visible.has(a)) L.push(agentRow(s, a, e));
		L.push("");
		return L;
	};
	const L: string[] = [];
	for (const o of orchs) if (!expanded(o)) {
		const mins = o.startedAt === undefined || o.endedAt === undefined ? "" : ` · ${Math.max(0, Math.round((o.endedAt - o.startedAt) / 60_000))} min`;
		L.push(`- ${o.state === "failed" ? "❌" : "✅"} Orchestrator ${o.n} · ${workers(o)}${mins}`);
	}
	if (L.length) L.push("");
	for (const o of expOrchs) {
		const label = o.state === "running" ? "▶ running" : o.state === "done" ? "✅ done" : "❌ failed";
		L.push(...table(`### 🎛 Orchestrator ${o.n} · ${label} · ${workers(o)}`, "Worker", s.agents.filter((a) => a.orch === o.id)));
		if (o.truncated) L.push("_+ more workers not shown_", "");
	}
	if (direct.length) L.push(...table("### Direct subagents", "Agent", direct));
	const hidden = candidates.length - visible.size;
	if (hidden > 0) L.push(`_+${hidden} older not shown_`, "");
	return L;
}

function question(q: Question, e: (t: string, max?: number) => string, hm: (ts: number) => string): string[] {
	const chip = q.severity === "critical" ? "🔴 critical" : "🟡 normal";
	const timing = q.deadline !== undefined ? `auto-default ${hm(q.deadline)}` : "no auto-default";
	const L = [`### ⏳ ${q.id} · ${chip} · asked ${hm(q.askedAt)} · ${timing}`, "", `**${e(q.text, 200)}**`, ""];
	q.options.forEach((opt, i) => L.push(`- ${q.id}.${i + 1} ${e(opt, 120)}${q.recommended === opt ? " ⭐" : ""}`));
	if (q.options.length) L.push("");
	if (q.recommended && !q.options.includes(q.recommended)) L.push(`⭐ recommended: ${e(q.recommended, 120)}`, "");
	if (q.why) L.push(`> why: ${e(q.why, 200)}`, "");
	return L;
}

const fmtUsd = (n: number) => (n < 0.005 ? "< $0.01" : `≈ $${n.toFixed(2)}`);

// head + direct subagents from the cost RPC; nested runs come from pi-subagents' nested event files (input/output only, no cache counts)
function usageLines(s: State): string[] {
	const L: string[] = [];
	const k = s.cost;
	if (k && k.input + k.output + k.cacheRead + k.cacheWrite > 0) {
		const tin = k.input + k.cacheRead + k.cacheWrite;
		const usd = k.usd > 0 ? ` · ${fmtUsd(k.usd)} list price (not your plan bill)` : "";
		L.push(`- usage: ${k.lowerBound ? "≥ " : ""}${fmtTokens(tin)} tokens in · ${fmtTokens(k.output)} out${usd}`);
	}
	const n = s.nestedCost;
	if (n && n.runs > 0) {
		const usd = n.usd > 0 ? ` · ${fmtUsd(n.usd)} list price` : "";
		L.push(`- nested runs (not in the usage above): ${n.runs} · ${n.lowerBound ? "≥ " : ""}${fmtTokens(n.input)} in · ${fmtTokens(n.output)} out (cache not counted)${usd}`);
	}
	return L;
}

function outcomeLines(s: State): string[] {
	const L: string[] = [];
	const c = s.counts ?? { model: 0, user: 0, timeout: 0 };
	const done = s.agents.filter((a) => a.state === "done").length;
	const failed = s.agents.filter((a) => a.state === "failed").length;
	const total = s.agents.length + (s.agentsDropped ?? 0);
	const nested = s.agents.reduce((n, a) => n + (a.nested ?? 0), 0);
	const nestedTrunc = s.agents.some((a) => a.nestedTruncated);
	const parts: string[] = [];
	if ((s.runs ?? 0) > 0) parts.push(`${s.runs} run${s.runs === 1 ? "" : "s"}`);
	if (total > 0) parts.push(`${total} subagent${total === 1 ? "" : "s"} (${done} ✅${failed ? `, ${failed} ❌` : ""})`);
	if (nested > 0) parts.push(`${nested}${nestedTrunc ? "+" : ""} nested`);
	if (c.model) parts.push(`${c.model} 🤖 decision${c.model === 1 ? "" : "s"}`);
	if (c.user) parts.push(`${c.user} 👤 answer${c.user === 1 ? "" : "s"}`);
	if (c.timeout) parts.push(`${c.timeout} ⏱ timed out`);
	if (parts.length) L.push(`- outcome: ${parts.join(" · ")}`);
	L.push(...usageLines(s));
	if (s.sum && s.sum.calls > 0) L.push(`- summarizer: ${s.sum.calls} call${s.sum.calls === 1 ? "" : "s"} · ${fmtTokens(s.sum.tokens)} tokens${s.sum.usd > 0 ? ` · ${fmtUsd(s.sum.usd)}` : ""}`);
	return L;
}
